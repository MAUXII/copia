import { getComponents } from "../registry"
import { SITE_URL } from "../site"

export type RegistryJson = ReturnType<typeof buildRegistryJson>

export function buildRegistryJson(root = "registry") {
  return {
    $schema: "https://ui.shadcn.com/schema/registry.json",
    name: "copia",
    homepage: SITE_URL,
    items: getComponents(root).map((meta) => ({
      name: meta.slug,
      type: "registry:component" as const,
      title: meta.name,
      description: meta.description,
      dependencies: meta.dependencies,
      files: [{ path: `registry/${meta.slug}/${meta.slug}.tsx`, type: "registry:component" as const }],
    })),
  }
}

/** Source of lib/demos.ts: a lazy import per component demo, keyed by slug. */
export function buildDemosModule(root = "registry"): string {
  const lines = getComponents(root).map(
    (meta) => `  "${meta.slug}": () => import("@/${root}/${meta.slug}/demo"),`,
  )
  return [
    "// Generated by `npm run registry`. Do not edit.",
    'import type { ComponentType } from "react"',
    "",
    "export const demos: Record<string, () => Promise<{ default: ComponentType }>> = {",
    ...lines,
    "}",
    "",
  ].join("\n")
}
